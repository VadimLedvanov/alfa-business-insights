package alpha.business.insight.core.qa.connectors;

import alpha.business.insight.core.qa.helpers.SyntheticPdf;
import io.qameta.allure.Allure;
import io.restassured.response.Response;
import io.restassured.specification.RequestSpecification;

import java.io.ByteArrayInputStream;
import java.net.URI;
import java.security.MessageDigest;
import java.util.HexFormat;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Consumer;

/** HTTP-клиент для работающего backend с безопасным приложением фактических ответов в Allure. */
public final class BackendClient {
    private final URI baseUri;
    private final Consumer<String> exchangeRecorder;

    /** Создаёт клиент backend с адресом сервера и записью истории HTTP-обменов. */
    public BackendClient(URI baseUri, Consumer<String> exchangeRecorder) {
        this.baseUri = baseUri;
        this.exchangeRecorder = exchangeRecorder;
    }

    /** Выполняет GET-запрос к backend и сохраняет безопасные сведения запроса и ответа. */
    public Response get(String path, String bearer) {
        URI uri = URI.create(baseUri + path);
        Map<String, String> headers = bearer == null ? Map.of() : Map.of("Authorization", "Bearer " + bearer);
        return Allure.step("GET " + uri.getPath(), () -> {
            String requestEvidence = attachRequest("GET", uri, headers, "(empty)");
            Response response = request(uri, headers).when().get();
            attachResponse(requestEvidence, response);
            return response;
        });
    }

    /** Загружает синтетический PDF через multipart-поля, сформированные Rest Assured. */
    public Response postMultipart(String path, SyntheticPdf.MultipartUpload upload, String bearer) {
        URI uri = URI.create(baseUri + path);
        Map<String, String> headers = bearer == null ? Map.of() : Map.of("Authorization", "Bearer " + bearer);
        String bodyDescription = "Query parameters: title=E2E synthetic report, publicationDate="
                + upload.publicationDate() + "\n" + upload.description() + "\nPDF: " + upload.pdf().length
                + " bytes; SHA-256=" + sha256(upload.pdf());
        return Allure.step("POST " + uri.getPath(), () -> {
            String requestEvidence = attachRequest("POST", uri, headers,
                    bodyDescription + "\nMultipart serialization is generated by Rest Assured.");
            addBinaryAttachment("Исходный PDF-файл запроса", "application/pdf", upload.pdf(), ".pdf");
            RequestSpecification request = request(uri, headers)
                    .queryParam("title", "E2E synthetic report")
                    .queryParam("publicationDate", upload.publicationDate())
                    .multiPart("publicationDate", upload.publicationDate())
                    .multiPart("file", upload.filename(), upload.pdf(), upload.contentType());
            Response response = request.when().post();
            attachResponse(requestEvidence, response);
            return response;
        });
    }

    /** Выполняет GET-запрос к внешней инфраструктуре и сохраняет его ответ в Allure. */
    public Response getExternal(URI uri, String description) {
        return Allure.step("GET " + uri.getPath() + " (" + description + ")", () -> {
            String requestEvidence = attachRequest("GET", uri, Map.of(), "(empty)");
            Response response = request(uri, Map.of()).when().get();
            attachResponse(requestEvidence, response);
            return response;
        });
    }

    /** Отправляет внешний JSON-запрос и сохраняет предоставленное тело вместе с ответом. */
    public Response postExternalJson(URI uri, String description, String requestBody) {
        Map<String, String> headers = Map.of("Content-Type", "application/json");
        return Allure.step("POST " + uri.getPath() + " (" + description + ")", () -> {
            String requestEvidence = attachRequest("POST", uri, headers, requestBody);
            Allure.addAttachment("HTTP request JSON body", "application/json", HttpEvidence.redact(requestBody));
            Response response = request(uri, headers).body(requestBody).when().post();
            attachResponse(requestEvidence, response);
            return response;
        });
    }

    /** Получает бинарный ответ, сохраняя оригинальные байты и их контрольную сумму. */
    public Response getBytes(String path, String bearer) {
        URI uri = URI.create(baseUri + path);
        Map<String, String> headers = bearer == null ? Map.of() : Map.of("Authorization", "Bearer " + bearer);
        return Allure.step("GET " + uri.getPath(), () -> {
            String requestEvidence = attachRequest("GET", uri, headers, "(empty)");
            Response response = request(uri, headers).when().get();
            byte[] bytes = response.asByteArray();
            String contentType = response.getContentType() == null
                    ? "application/octet-stream" : response.getContentType();
            String responseInfo = responseInfo(requestEvidence, response, "Binary response: " + bytes.length
                    + " bytes; SHA-256=" + sha256(bytes));
            Allure.addAttachment("HTTP response", "text/plain", responseInfo);
            if (HttpEvidence.isPdf(contentType)) {
                addBinaryAttachment("Ответный PDF-файл", "application/pdf", bytes, ".pdf");
            } else {
                addBinaryAttachment("Ответное бинарное тело", contentType, bytes, ".bin");
            }
            exchangeRecorder.accept("RESPONSE\n" + responseInfo);
            return response;
        });
    }

    /** Создаёт отдельную спецификацию запроса с таймаутами, без redirect и повторов. */
    private RequestSpecification request(URI uri, Map<String, String> headers) {
        RequestSpecification request = RestAssuredRequests.forUri(uri);
        headers.forEach(request::header);
        return request;
    }

    /** Прикладывает сведения о заданных параметрах запроса, отдельно обозначая multipart-данные. */
    private String attachRequest(String method, URI uri, Map<String, String> headers, String body) {
        StringBuilder headerText = new StringBuilder();
        headers.forEach((name, value) -> headerText.append(name).append(": ").append(value).append('\n'));
        String evidence = "Request specification (supplied values; not a wire capture): " + method + " " + uri
                + "\nHeaders:\n" + HttpEvidence.redact(headerText.toString()).stripTrailing() + "\nBody:\n"
                + HttpEvidence.redact(body);
        exchangeRecorder.accept("REQUEST\n" + evidence);
        Allure.addAttachment("HTTP request " + method, "text/plain", evidence);
        return evidence;
    }

    /** Прикладывает тело и заголовки фактического ответа, замаскировав секретные значения. */
    private void attachResponse(String requestEvidence, Response response) {
        String body = response.asString();
        String evidence = responseInfo(requestEvidence, response, body);
        Allure.addAttachment("HTTP response", "text/plain", evidence);
        String contentType = response.getContentType() == null ? "text/plain" : response.getContentType();
        String attachmentType = contentType.toLowerCase(java.util.Locale.ROOT).contains("application/json")
                ? "application/json" : "text/plain";
        Allure.addAttachment("HTTP response body", attachmentType, HttpEvidence.redact(body));
        exchangeRecorder.accept("RESPONSE\n" + evidence);
    }

    /** Форматирует полученный от сервера статус, заголовки и тело. */
    private static String responseInfo(String requestEvidence, Response response, String body) {
        return requestEvidence + "\n\nResponse:\nHTTP " + response.statusCode() + "\nHeaders:\n"
                + HttpEvidence.headers(responseHeaders(response)) + "\nBody:\n" + HttpEvidence.redact(body);
    }

    /** Преобразует заголовки Rest Assured в формат общего средства редактирования evidence. */
    private static Map<String, List<String>> responseHeaders(Response response) {
        Map<String, List<String>> headers = new LinkedHashMap<>();
        response.getHeaders().asList().forEach(header -> headers
                .computeIfAbsent(header.getName(), ignored -> new java.util.ArrayList<>()).add(header.getValue()));
        return headers;
    }

    /** Добавляет бинарные байты с длиной и SHA-256 в материалы Allure. */
    private static void addBinaryAttachment(String name, String contentType, byte[] bytes, String extension)
            throws Exception {
        Allure.addAttachment(name + " (" + bytes.length + " bytes; SHA-256=" + sha256(bytes) + ")",
                contentType, new ByteArrayInputStream(bytes), extension);
    }

    /** Возвращает SHA-256 для проверки неизменности бинарного материала. */
    private static String sha256(byte[] bytes) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes));
        } catch (java.security.NoSuchAlgorithmException impossible) {
            throw new AssertionError(impossible);
        }
    }
}
